INSERT INTO party_categories(id,name,name_key,parent_id)
SELECT gen_random_uuid(),r.category,lower(r.category),p.id
FROM (SELECT DISTINCT category,parent_name FROM party_category_review) r
LEFT JOIN party_categories p ON p.parent_id IS NULL AND p.name=r.parent_name
WHERE NOT EXISTS (SELECT 1 FROM party_categories c WHERE c.name_key=lower(r.category) AND c.parent_id IS NOT DISTINCT FROM p.id);
UPDATE party_word_bank w SET category=r.category,category_id=target.id,version=w.version+1,updated_at=now()
FROM party_category_review r
JOIN party_categories source ON source.name=r.old_category AND source.parent_id=(SELECT id FROM party_categories WHERE parent_id IS NULL AND name='游戏')
LEFT JOIN party_categories parent ON parent.name=r.parent_name AND parent.parent_id IS NULL
JOIN party_categories target ON target.name_key=lower(r.category) AND target.parent_id IS NOT DISTINCT FROM parent.id
WHERE w.answer=r.answer AND w.category_id=source.id;
